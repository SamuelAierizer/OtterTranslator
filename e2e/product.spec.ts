import {test,expect} from '@playwright/test';
import path from 'node:path';
import { readFile } from 'node:fs/promises';
import AdmZip from 'adm-zip';

test('browser product flow through real local SMTP and identity translation',async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
  await page.getByLabel('Email address').fill('demo@example.com');
  await page.getByRole('button',{name:'Send sign-in link'}).click();
  await expect(page.getByRole('status')).toContainText('a sign-in link is on its way');
  const mail=await (await request.get('/__test/mail')).json();
  const link=mail.text.match(/http:\/\/127\.0\.0\.1:3011\/auth\/verify\?token=[a-f0-9]+/)?.[0];
  expect(link).toBeTruthy();await page.goto(link);
  await expect(page.getByRole('heading',{name:'Translate a document'})).toBeVisible();
  const cookie=(await page.context().cookies()).find(c=>c.name==='session');expect(cookie?.httpOnly).toBe(true);expect(cookie?.path).toBe('/');
  await page.getByLabel('Word document').setInputFiles(path.resolve('test/fixtures/hyperlink.docx'));
  await page.getByRole('combobox',{name:'Source language'}).selectOption('ro');
  await page.getByRole('combobox',{name:'Target language'}).selectOption('hu');
  await page.getByRole('button',{name:'Translate document',exact:true}).click();
  await expect(page.getByRole('link',{name:'Download DOCX'})).toBeVisible();
  await expect(page.locator('.job').first()).toContainText('RO to HU');
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Download DOCX'}).click()]);
  const bytes=await readFile((await download.path())!);expect(new AdmZip(bytes).readAsText('word/document.xml')).toContain('hyperlink');
  await page.screenshot({path:'test-results/product-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/product-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByLabel('Word document').setInputFiles({name:'too-large.docx',mimeType:'application/octet-stream',buffer:Buffer.alloc(2097153)});
  await page.getByRole('button',{name:'Translate document',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Maximum upload size');
  await page.getByLabel('Word document').setInputFiles({name:'invalid.docx',mimeType:'application/octet-stream',buffer:Buffer.from('not docx')});
  await page.getByRole('button',{name:'Translate document',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('not a valid DOCX');
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
  await page.goto(link);await expect(page.getByRole('status')).toContainText('expired or was already used');
  expect(errors).toEqual([]);
});
